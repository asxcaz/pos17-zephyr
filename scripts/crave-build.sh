#!/usr/bin/env bash
# Run inside the PixelOS Crave Clone root via:
# crave run --no-patch -- "curl -fsSL https://raw.githubusercontent.com/asxcaz/pos17-zephyr/main/scripts/crave-build.sh | bash"
set -Eeuo pipefail

ROM_ROOT="$PWD"
MANIFEST_URL="https://github.com/PixelOS-AOSP/android_manifest.git"
MANIFEST_BRANCH="seventeen"
LOCAL_MANIFEST_URL="https://raw.githubusercontent.com/asxcaz/pos17-zephyr/main/local_manifests/zephyr.xml"
KERNEL_URL="https://gitlab.com/almightygodthor/android_device_oplus_zephyr-kernel.git"
VENDOR_URL="https://gitlab.com/almightygodthor/proprietary_vendor_oplus_zephyr.git"
DEVICE_DIR="$ROM_ROOT/device/oplus/zephyr"
KERNEL_DIR="$ROM_ROOT/device/oplus/zephyr-kernel"
VENDOR_DIR="$ROM_ROOT/vendor/oplus/zephyr"

say() { printf '\n[%s] %s\n' "$(date '+%F %T')" "$*"; }
fail() { echo "ERROR: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || fail "Required command not found: $1"; }

need repo
need git
need curl

[[ -f "$ROM_ROOT/build/envsetup.sh" || -d "$ROM_ROOT/.repo" ]] || {
    echo "Run this script from the root of your Crave Clone workspace." >&2
    echo "Current directory: $ROM_ROOT" >&2
    exit 2
}

# Restore only the two upstream files this script patches, so reruns can sync
# cleanly. Keep any unrelated local source edits intact.
if [[ -e "$DEVICE_DIR/.git" ]]; then
    git -C "$DEVICE_DIR" checkout -- AndroidProducts.mk vendorsetup.sh 2>/dev/null || true
fi
if [[ -f "$DEVICE_DIR/custom_zephyr.mk" ]] && grep -q "Generated by pos17-zephyr" "$DEVICE_DIR/custom_zephyr.mk"; then
    rm -f "$DEVICE_DIR/custom_zephyr.mk"
fi
rm -f "$DEVICE_DIR/vendorsetup.sh.disabled"

say "Initialize PixelOS Android 17 manifest"
repo init -u "$MANIFEST_URL" -b "$MANIFEST_BRANCH" --git-lfs --depth=1

# Remove local manifests inherited from the base Crave project before applying
# only this project's reviewed device manifest. This runs on the build node,
# inside crave run, not in the Devspace shell.
rm -rf "$ROM_ROOT/.repo/local_manifests"
mkdir -p "$ROM_ROOT/.repo/local_manifests"
curl -fsSL "$LOCAL_MANIFEST_URL" -o "$ROM_ROOT/.repo/local_manifests/zephyr.xml"

say "Synchronize PixelOS and the device GitHub repositories via Crave resync"
[[ -x /opt/crave/resync.sh ]] || fail "/opt/crave/resync.sh is unavailable on this Crave build node; refusing to fall back to raw repo sync."
/opt/crave/resync.sh

[[ -f "$DEVICE_DIR/lineage_zephyr.mk" ]] || fail "Device product makefile not found at $DEVICE_DIR/lineage_zephyr.mk"
[[ -f "$DEVICE_DIR/AndroidProducts.mk" ]] || fail "AndroidProducts.mk not found; local manifest sync may have failed"

sync_default_repo() {
    local url="$1"
    local dest="$2"
    local label="$3"
    local default_ref branch

    say "Resolve the default branch for $label"
    default_ref="$(git ls-remote --symref "$url" HEAD | awk '$1 == "ref:" && $3 == "HEAD" { print $2; exit }')"
    [[ -n "$default_ref" ]] || fail "Cannot resolve default branch for $label from $url"
    branch="${default_ref#refs/heads/}"
    echo "$label default branch: $branch"

    if [[ -e "$dest" && ! -d "$dest/.git" ]]; then
        fail "$dest exists but is not a Git checkout; refusing to overwrite it."
    fi

    if [[ ! -d "$dest/.git" ]]; then
        mkdir -p "$(dirname "$dest")"
        git clone --depth=1 "$url" "$dest"
    else
        git -C "$dest" remote set-url origin "$url"
        git -C "$dest" fetch --depth=1 origin "$branch"
        git -C "$dest" checkout -B "$branch" FETCH_HEAD
        git -C "$dest" reset --hard FETCH_HEAD
    fi

    if command -v git-lfs >/dev/null 2>&1; then
        git -C "$dest" lfs pull || fail "Git LFS pull failed for $label"
    fi
}

say "Fetch kernel prebuilt and proprietary vendor files from their default branches"
sync_default_repo "$KERNEL_URL" "$KERNEL_DIR" "Zephyr kernel prebuilt"
sync_default_repo "$VENDOR_URL" "$VENDOR_DIR" "Zephyr proprietary vendor"

say "Validate required device files"
for path in \
    "$KERNEL_DIR/Image.gz" \
    "$KERNEL_DIR/dtb/mt6895.dtb" \
    "$KERNEL_DIR/modules/vendor_dlkm.modules.load" \
    "$KERNEL_DIR/modules/vendor_ramdisk.modules.load" \
    "$KERNEL_DIR/modules/vendor_ramdisk.modules.load.recovery" \
    "$VENDOR_DIR/BoardConfigVendor.mk"; do
    [[ -e "$path" ]] || fail "Required device file is missing: $path"
done
kernel_size="$(stat -c '%s' "$KERNEL_DIR/Image.gz")"
(( kernel_size > 1000000 )) || fail "Image.gz is only $kernel_size bytes. Check whether Git LFS has downloaded the real image."
echo "Kernel Image.gz: $kernel_size bytes"

say "Create PixelOS custom_zephyr product configuration"
sed \
    -e 's@vendor/lineage/config/common_full_phone.mk@vendor/custom/config/common_full_phone.mk@' \
    -e 's@PRODUCT_NAME := lineage_zephyr@PRODUCT_NAME := custom_zephyr@' \
    "$DEVICE_DIR/lineage_zephyr.mk" > "$DEVICE_DIR/custom_zephyr.mk"

if ! grep -q 'PRODUCT_NAME := custom_zephyr' "$DEVICE_DIR/custom_zephyr.mk"; then
    fail "Failed to convert lineage_zephyr.mk to the PixelOS custom_zephyr product."
fi

cat > "$DEVICE_DIR/AndroidProducts.mk" <<'EOF'
# Generated by pos17-zephyr for local PixelOS builds.
PRODUCT_MAKEFILES := \
    $(LOCAL_DIR)/lineage_zephyr.mk \
    $(LOCAL_DIR)/custom_zephyr.mk
EOF

# The upstream script applies Android 16 QPR2 IMS and fixed framework/Aperture
# cherry-picks. Disable it locally; do not silently apply those commits to 17.
if [[ -f "$DEVICE_DIR/vendorsetup.sh" ]]; then
    mv "$DEVICE_DIR/vendorsetup.sh" "$DEVICE_DIR/vendorsetup.sh.disabled"
fi

if [[ "${POS17_SKIP_BUILD:-0}" == "1" ]]; then
    say "POS17_SKIP_BUILD=1: source sync and device preflight finished; compilation skipped."
    exit 0
fi

say "Configure PixelOS build target"
cd "$ROM_ROOT"
source build/envsetup.sh
lunch custom_zephyr-cp2a-userdebug

JOBS="${POS17_JOBS:-$(nproc --all)}"
[[ "$JOBS" =~ ^[0-9]+$ ]] && (( JOBS > 0 )) || fail "POS17_JOBS must be a positive integer."

say "Compile PixelOS"
set -o pipefail
m pixelos -j"$JOBS" 2>&1 | tee "$ROM_ROOT/build-zephyr.log"

PRODUCT_OUT="$ROM_ROOT/out/target/product/zephyr"
[[ -d "$PRODUCT_OUT" ]] || fail "Build output directory not found: $PRODUCT_OUT"
mapfile -t ROM_ZIPS < <(find "$PRODUCT_OUT" -maxdepth 1 -type f -name '*.zip' -print)
(("${#ROM_ZIPS[@]}" > 0)) || fail "Build completed but no ZIP was found in $PRODUCT_OUT"

say "Build succeeded. Candidate ZIP files:"
printf '  %s\n' "${ROM_ZIPS[@]}"
say "Use crave pull from the Devspace to retrieve the ZIP. This script does not flash any device."
