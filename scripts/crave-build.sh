sync_default_repo() {
    local url="$1"
    local dest="$2"
    local label="$3"
    local default_ref branch

    say "Resolve the default branch for $label"
    default_ref="$(git ls-remote --symref "$url" HEAD | awk '$1 == "ref:" && $3 == "HEAD" { print $2; exit }')"
    [[ -n "$default_ref" ]] || fail "Cannot resolve default branch for $label from $url"
    branch="${default_ref#refs/heads/}"
    echo "$label default branch: $branch"

    if [[ -e "$dest" && ! -d "$dest/.git" ]]; then
        fail "$dest exists but is not a Git checkout; refusing to overwrite it."
    fi

    if [[ ! -d "$dest/.git" ]]; then
        mkdir -p "$(dirname "$dest")"
        git clone --depth=1 "$url" "$dest"
    else
        git -C "$dest" remote set-url origin "$url"
        git -C "$dest" fetch --depth=1 origin "$branch"
        git -C "$dest" checkout -B "$branch" FETCH_HEAD
        git -C "$dest" reset --hard FETCH_HEAD
    fi

    if command -v git-lfs >/dev/null 2>&1; then
        git -C "$dest" lfs pull || fail "Git LFS pull failed for $label"
    fi
}

